/**
 * Настройки поведения системы.
 *
 * TypeScript, а не JSON — чтобы у каждого параметра стояло объяснение,
 * за что он отвечает и откуда взялось значение. В JSON комментариев нет,
 * а числа без объяснения через полгода превращаются в магические константы,
 * которые страшно трогать.
 *
 * Здесь только то, что описывает СИСТЕМУ. Всё, что описывает конкретного
 * пользователя (уровень языка), живёт в user/profile.json. Секреты — в .env.
 *
 * Полная карта: CONFIG.md
 */
export const tuning = {
  /** Примеры предложений из книги, сохраняемые к каждому слову. */
  contexts: {
    /**
     * Сколько примеров хранить на лемму.
     * Больше, чем показываем: глазами читаются три, а модели при группировке
     * по значениям нужен весь разброс — пропущенное второе значение слова
     * потом ничем не восстановить.
     */
    maxStored: 10,

    /**
     * Минимальная длина примера в символах.
     * Отсекает обрывки реплик вроде «"No," he said», из которых значение
     * слова не восстановить.
     */
    minLength: 25,

    /** Сколько примеров показывать при отборе. Больше трёх глазами не читается. */
    maxShown: 3,
  },

  /** Отбор кандидатов в карточки. */
  scoring: {
    /**
     * Нижняя граница полезности по частотности.
     * Ниже zipf 2.0 слово встречается реже раза на 10 млн слов — то есть
     * в жизни не встретится никогда. lifeValue таких слов = 0.
     */
    floorZipf: 2.0,

    /**
     * Насыщение bookValue: столько вхождений в книге уже дают максимум.
     * Разница между 40 и 80 вхождениями для читателя несущественна —
     * слово в обоих случаях ключевое для книги.
     */
    saturation: 40,

    /**
     * Со скольких книг слово предлагается вопреки порогу знания.
     * Слово выше knownZipf, попавшееся в трёх книгах, означает, что в ТВОЁМ
     * круге чтения оно частотнее, чем в корпусе wordfreq (собранном из веба
     * и субтитров). Свидетельство из собственного чтения сильнее глобальной
     * статистики.
     */
    historyOverride: 3,

    /**
     * Граница маршрутизации по lifeValue.
     * Выше — колода speak, ниже — read. Основание: продукция включает
     * узнавание (умеешь произнести — узнаешь при чтении), поэтому при
     * высоких значениях по обеим осям выигрывает speak.
     */
    speakThreshold: 0.5,

    /**
     * Во сколько раз выше ожидаемого, чтобы пометить «проверь значение».
     * Ловит и настоящие ловушки (dolphin у Хемингуэя — корифена, а не
     * дельфин; stern — корма, а не «суровый»), и просто тематически частое
     * (breeze, turtle). Различить статистикой нельзя, поэтому это ПОМЕТКА
     * для глаз, а не решение о колоде.
     */
    checkSenseRatio: 50,

    /**
     * Веса осей в приоритете внутри колоды speak.
     * Для активного словаря важнее общая применимость слова, чем то,
     * сколько раз оно встретилось в конкретной книге.
     */
    speakWeights: { life: 0.7, book: 0.3 },

    /**
     * Веса осей для колоды read.
     * Здесь наоборот: скиф и гарпун нужны ради этой книги, а не ради жизни.
     */
    readWeights: { life: 0.2, book: 0.8 },
  },

  /** Сколько кандидатов показывать при отборе. */
  review: {
    /**
     * Раздельно, а не общим числом.
     * Формулы приоритета у колод разные, и общий топ даёт перекос:
     * на реальной книге топ-40 состоял из 37 speak и 3 read, за бортом
     * остались skiff ×48, oar ×25, harpoon ×20 — вся характерная лексика.
     */
    topSpeak: 30,
    topRead: 15,
  },

  /** Генерация карточек. */
  generation: {
    model: 'claude-sonnet-4-6',
    maxTokens: 2000,

    /**
     * Попыток на карточку, не прошедшую проверки.
     * Карточку из Noji нельзя ни исправить, ни удалить, поэтому чинить
     * приходится до экспорта. Каждая попытка — отдельный запрос.
     */
    maxAttempts: 3,

    /**
     * Слов за прогон, если не задан --limit.
     * Держим небольшим: чистая speak-карточка стоит 2 запроса (генерация
     * плюс проверка на неоднозначность), с двумя переделками — 6.
     */
    defaultLimit: 10,
  },
} as const;

export type Tuning = typeof tuning;