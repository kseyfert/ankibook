/**
 * Субтитры SRT → блоки текста.
 *
 * Формат простой: пронумерованные блоки, в каждом номер, строка тайм-кода
 * и одна-две строки реплики. Разбирается вручную, потому что officeparser
 * его не знает, а сводить к нему нечего — это не документ, а список реплик.
 */

/** `00:03:24,067 --> 00:03:28,200`. Точка вместо запятой встречается тоже. */
const TIMECODE = /^\d{1,2}:\d{2}:\d{2}[,.]\d{1,3}\s*-->\s*\d{1,2}:\d{2}:\d{2}[,.]\d{1,3}/;

/** Порядковый номер блока. */
const INDEX = /^\d+$/;

/** `<i>`, `</i>`, `<font color="#fff">` — курсив и цвет речью не являются. */
const TAG = /<[^>]*>/g;

/** `{\an8}` — позиционирование на экране. */
const POSITION = /\{[^}]*\}/g;

/**
 * `[music]`, `[door slams]` — пометки о звуке, а не реплики.
 *
 * Для словаря это шум: слова из них в книге не звучали, их никто не говорил.
 */
const CUE = /\[[^\]]*\]/g;

/**
 * Одна реплика в одну строку.
 *
 * Субтитры разбиты по ширине экрана, а не по смыслу: «In this world, men» /
 * «do whatever they want» — это одно предложение, разрезанное пополам.
 * Оставь как есть — и в контексты к словам попадут обрывки.
 */
function clean(block: string): string {
  let lines = block.split(/\r?\n/).map((l) => l.trim()).filter(Boolean);

  // Номер отбрасывается, только если он ПЕРВЫЙ и за ним тайм-код. Иначе
  // реплика, состоящая из одного числа («1999.»), исчезла бы вместе с ним.
  if (lines.length > 1 && INDEX.test(lines[0]) && TIMECODE.test(lines[1])) {
    lines = lines.slice(1);
  }

  return lines
    .filter((l) => !TIMECODE.test(l))
    .map((l) => l.replace(TAG, '').replace(POSITION, '').replace(CUE, ''))
    .join(' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Блоки, а не готовый текст: дальше их склеит `assemble` через пустую строку,
 * как абзацы. Реплики должны оставаться разделёнными — иначе выборка
 * контекстов перескочит границу и слепит слова двух говорящих в одну фразу.
 */
export function parseSrt(raw: string): string[] {
  return raw
    // BOM: файлы субтитров часто приходят из редакторов, которые его ставят,
    // и без этого первый номер блока не совпал бы с регулярным выражением.
    .replace(/^﻿/, '')
    .split(/\r?\n[ \t]*\r?\n/)
    .map(clean)
    .filter(Boolean);
}
